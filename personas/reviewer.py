        "\n🟡 可疑 — 单源数据/表述模糊/缺少反面证据 → 值得注意"
        "\n\n## 第一轮输出格式"
        "\n```"
        "\n## 总体印象"
        "\n{一句话定性最大风险在哪个层面}"
        "\n优先验证：#N #N"
        "\n"
        "\n## 怀疑清单"
        "\n#1 🔴 [事实] 「{原文引用}」{节名} — {一句话理由}"
